// Write docs/i18n/<code>-review.md for every non-default locale: a table of
// key | English | translation for the UI strings, and the preset
// translations, so a native speaker can review (and comment on) each line.
//   node scripts/i18n-review.mjs          write the files (npm run i18n-review)
//   node scripts/i18n-review.mjs --check  report stale files (npm run check);
//                                         like the README table, a warning
//                                         on pull requests, else an error
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { basename, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { PRESETS_DIR, readPresets } from "./bundle-presets.mjs";
import { flatten, I18N_DIR, render } from "./check-locales.mjs";
import { cell, staleSeverity } from "./update-readme.mjs";

const ROOT = fileURLToPath(new URL("..", import.meta.url));
export const REVIEW_DIR = join(ROOT, "docs", "i18n");

/**
 * Presets whose translations are new and not yet reviewed: listed first, under
 * their own heading, so the reviewer finds them. Empty `ids` once reviewed.
 */
export const NEW_FOR_REVIEW = { heading: "Changed: needs review", ids: ["jee-main"] };

/**
 * The review document for one locale.
 * @param {{ code: string, name: string, status: string }} locale
 * @param {Record<string, unknown>} en English strings
 * @param {Record<string, unknown>} own the locale's strings
 * @param {object[]} presets presets in display order (with translations)
 * @param {string} englishName the language's English name, e.g. "Hindi"
 * @param {{ heading: string, ids: string[] }} [newForReview] presets to list
 *   first under their own heading (left out of "Exam presets")
 */
export function reviewMarkdown(locale, en, own, presets, englishName, newForReview = { heading: "", ids: [] }) {
  const ownMap = new Map(flatten(own));
  const missing = "_(missing: English is shown)_";
  const row = (...cells) => `| ${cells.join(" | ")} |`;
  const text = (v) => cell(render(v)).replace(/\n/g, " ");
  const lines = [
    `# ${englishName} (${locale.name}) translation review`,
    "",
    `<!-- GENERATED by scripts/i18n-review.mjs (npm run i18n-review). Do not edit by hand. -->`,
    "",
    `Every user-visible string, English next to ${englishName}, for a native speaker to check. To ask for a change, comment on the line in the pull request, or edit \`src/ui/i18n/${locale.code}.js\` (UI) or the preset's \`translations.${locale.code}\` (exams) and run \`npm run i18n-review\`.`,
    "",
    "Placeholders like `{w}` are filled in by the app (numbers, file names, exam names). Numbers stay in Western digits; \"ExamSnap\" is never translated.",
    "",
    "## UI strings",
    "",
    row("Key", "English", englishName),
    row("---", "---", "---"),
  ];
  for (const [key, value] of flatten(en)) {
    lines.push(row(`\`${key}\``, text(value), ownMap.has(key) ? text(ownMap.get(key)) : missing));
  }
  const presetRows = (p) => {
    const t = p.translations?.[locale.code] ?? {};
    const fields = [
      ["name", p.name, t.name],
      ...(p.notes ? [["notes", p.notes, t.notes]] : []),
      ...p.documents.flatMap((d) => [
        [`documents.${d.id}.label`, d.label, t.documents?.[d.id]?.label],
        ...(d.notes ? [[`documents.${d.id}.notes`, d.notes, t.documents?.[d.id]?.notes]] : []),
      ]),
    ];
    lines.push("", `### \`${p.id}\``, "", row("Field", "English", englishName), row("---", "---", "---"));
    for (const [field, english, translated] of fields) {
      lines.push(row(`\`${field}\``, text(english), translated ? text(translated) : "_(English)_"));
    }
  };
  const isNew = (p) => newForReview.ids.includes(p.id);
  const fresh = presets.filter(isNew);
  if (fresh.length) {
    lines.push("", `## ${newForReview.heading}`, "", "Draft translations not yet reviewed by a native speaker. Once reviewed, they move to \"Exam presets\" below.");
    fresh.forEach(presetRows);
  }
  lines.push("", "## Exam presets", "", `Optional per preset (\`translations.${locale.code}\` in \`presets/<id>.json\`); anything not translated is shown in English.`);
  presets.filter((p) => !isNew(p)).forEach(presetRows);
  return `${lines.join("\n")}\n`;
}

const ENGLISH_NAMES = { hi: "Hindi" };

/**
 * Build every locale's review document.
 * @returns {Promise<Map<string, string>>} file path -> markdown
 */
export async function reviewDocs({ i18nDir = I18N_DIR, presetsDir = PRESETS_DIR, outDir = REVIEW_DIR } = {}) {
  const load = async (f) => import(pathToFileURL(join(i18nDir, f)).href);
  const { LOCALES, DEFAULT_LOCALE } = await load("locales.js");
  const en = (await load(`${DEFAULT_LOCALE}.js`)).STRINGS;
  const presets = await readPresets(presetsDir);
  const out = new Map();
  for (const l of LOCALES.filter((x) => x.code !== DEFAULT_LOCALE)) {
    const own = (await load(`${l.code}.js`)).STRINGS;
    out.set(join(outDir, `${l.code}-review.md`), reviewMarkdown(l, en, own, presets, ENGLISH_NAMES[l.code] ?? l.code, NEW_FOR_REVIEW));
  }
  return out;
}

/** @returns {Promise<string[]>} stale (or missing) files */
export async function run({ check = false, ...options } = {}) {
  const stale = [];
  for (const [path, md] of await reviewDocs(options)) {
    const current = await readFile(path, "utf8").catch(() => null);
    if (current === md) continue;
    stale.push(path);
    if (!check) {
      await mkdir(join(path, ".."), { recursive: true });
      await writeFile(path, md);
    }
  }
  return stale;
}

if (process.argv[1] && basename(process.argv[1]) === basename(fileURLToPath(import.meta.url))) {
  const check = process.argv.includes("--check");
  const stale = (await run({ check })).map((p) => p.slice(ROOT.length));
  if (!check) {
    console.log(stale.length ? `Wrote ${stale.join(", ")}.` : "Translation review files already up to date.");
  } else if (!stale.length) {
    console.log("Translation review files are up to date.");
  } else if (staleSeverity(process.env) === "error") {
    console.error(`ERROR ${stale.join(", ")} out of date. Run: npm run i18n-review`);
    process.exit(1);
  } else {
    console.log(`::warning title=Translation review::${stale.join(", ")} out of date. The maintainer regenerates it before merging (npm run i18n-review).`);
  }
}
